import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import Rectangle
import numpy as np
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent
BW, BH = 92, 44


def new(W, H):
    f, a = plt.subplots(figsize=(W / 100, H / 100), dpi=130)
    a.set_xlim(0, W)
    a.set_ylim(H, 0)
    a.axis("off")
    return f, a


def box(a, t, x, y, w=BW, h=BH, fs=18, dashed=False):
    a.add_patch(Rectangle((x, y), w, h, fill=False, ec="k", lw=1.7,
                          ls="--" if dashed else "-"))
    a.text(x + w / 2, y + h / 2, t, ha="center", va="center", fontsize=fs)


def line(a, pts, arrow=True, dashed=False):
    for p, q in zip(pts, pts[1:]):
        a.plot([p[0], q[0]], [p[1], q[1]], "k", lw=1.3,
               ls="--" if dashed else "-")
    if arrow:
        p, q = pts[-2], pts[-1]
        d = np.array(q, float) - np.array(p, float)
        d /= np.linalg.norm(d)
        a.annotate("", xy=q, xytext=tuple(np.array(q, float) - d),
                   arrowprops=dict(arrowstyle="-|>", color="k", lw=1.3, mutation_scale=14))


def lab(a, t, x, y, fs=11):
    a.text(x, y, t, ha="center", va="center", fontsize=fs, style="italic")


def save(f, name):
    f.savefig(OUT / name, bbox_inches="tight", facecolor="white")
    plt.close(f)
    print(f"  {name}")


